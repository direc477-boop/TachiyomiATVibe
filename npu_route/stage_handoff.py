"""Stage E's device-lib handoff from the installed SDK wheel into the neutral epic dir.

Source of truth: the SAME ai-edge-litert-sdk-qualcomm wheel that performs the
compile - version-identical device libs by construction. Writes files + manifest.
"""
import hashlib
import os
import re
import shutil
import site
import sys

HANDOFF = "/scratch/npu-handoff"  # container-visible; copied to epic scratch afterwards
ARTIFACT = sys.argv[1] if len(sys.argv) > 1 else "/scratch/out/mcv2-fp32-b6-int32idx_float32_Qualcomm_SM8650_apply_plugin.tflite"
WANT = [
    "libQnnHtp.so",
    "libQnnSystem.so",
    "libQnnHtpV75Stub.so",
]
SKEL_GLOBS = ["hexagon-v75/unsigned/libQnnHtpV75Skel.so", "hexagon-v75/libQnnHtpV75Skel.so"]

roots = set()
for sp in site.getsitepackages() + [site.getusersitepackages()]:
    p = os.path.join(sp, "ai_edge_litert_sdk_qualcomm", "data", "lib")
    if os.path.isdir(p):
        roots.add(p)
if not roots:
    print("FATAL: ai_edge_litert_sdk_qualcomm data/lib not found")
    sys.exit(2)
root = sorted(roots)[0]
print("[handoff] sdk lib root:", root)
for d in sorted(os.listdir(root)):
    print("  -", d)

os.makedirs(HANDOFF, exist_ok=True)
manifest = ["# npu-handoff manifest (generated by D)", ""]
picked = []

def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()

def version_strings(path, limit=6):
    data = open(path, "rb").read()
    strs = re.findall(rb"[ -~]{8,}", data)
    hits = []
    for s in strs:
        t = s.decode("ascii", "ignore")
        if re.search(r"\b2\.\d{1,2}\.\d{1,3}", t) and len(t) < 80 and t not in hits:
            hits.append(t)
        if len(hits) >= limit:
            break
    return hits

# host arch dir name for version context
for sub in ["aarch64-android", "hexagon-v75"]:
    d = os.path.join(root, sub)
    if os.path.isdir(d):
        print(f"[handoff] {sub} contents:", sorted(os.listdir(d)))

for name in WANT:
    found = None
    for base, _, files in os.walk(os.path.join(root, "aarch64-android")):
        if name in files:
            found = os.path.join(base, name)
            break
    if not found:
        print(f"WARN: {name} not found under aarch64-android")
        continue
    dst = os.path.join(HANDOFF, name)
    shutil.copyfile(found, dst)
    picked.append((name, found, dst))

skel_rel = None
for g in SKEL_GLOBS:
    cand = os.path.join(root, g)
    if os.path.isfile(cand):
        dst = os.path.join(HANDOFF, os.path.basename(g))
        shutil.copyfile(cand, dst)
        skel_rel = g
        picked.append((os.path.basename(g), cand, dst))
        break

for name, src, dst in picked:
    size = os.path.getsize(dst)
    digest = sha256(dst)
    vers = "; ".join(version_strings(dst))
    manifest += [
        f"## {name}",
        f"- source wheel path: {os.path.relpath(src, root)}",
        f"- sha256: {digest}",
        f"- bytes: {size}",
        f"- version-ish strings: {vers or '(none found)'}",
        "",
    ]
    print(f"[handoff] {name}: {size} B sha256={digest}")

manifest += [
    "## env",
    f"- sdk lib root: {root}",
    f"- skel relative path in wheel: {skel_rel}",
    "",
]
try:
    import ai_edge_litert_sdk_qualcomm as q  # noqa: PLC0415

    manifest.append(f"- path_to_sdk_libs(): {q.path_to_sdk_libs()}")
except Exception as e:  # noqa: BLE001
    manifest.append(f"- sdk import failed: {e}")

with open(os.path.join(HANDOFF, "MANIFEST.md"), "w", newline="\n") as f:
    f.write("\n".join(manifest))

# --- compiled NPU artifact section ---
if os.path.isfile(ARTIFACT):
    dst = os.path.join(HANDOFF, os.path.basename(ARTIFACT))
    shutil.copyfile(ARTIFACT, dst)
    size = os.path.getsize(dst)
    digest = sha256(dst)
    artifact_section = [
        "## compiled artifact",
        f"- file: {os.path.basename(ARTIFACT)}",
        f"- sha256: {digest}",
        f"- bytes: {size}",
        "- provenance: preserved B6-v1 FP32 (sha256 7923be0cb3b5370ba3aeb8cc076842b7b290a73cbd14cc967758bdeb739ceb82)",
        "- compile: ai-edge-litert 2.3.0 aot_compile, target Qualcomm SM8650 (HTP v75), QAIRT 2.50.0.260828 (wheel-bundled),"
        " ubuntu 22.04 x86_64 container, default compile options (no CompilationConfig overrides)",
        "- partition result: 590/590 ops -> 1 HTP partition, full offload, no CPU fallback fragment",
        "- tensor contract: input FP32 NCHW [1,5,704,512] 'input' / output FP32 NHWC [1,704,512,3] 'rgb', signature serving_default",
        "- runtime note: dispatch-format produced by host line 2.3.0; device AAR line 2.3.2 first, entire-APK 2.3.0-line fallback authorized (E's ledger)",
        "- init taxonomy: pure AOT-load (backend dlopen + QNN context deserialize + buffer registration);"
        " CompilerPlugin JIT engagement on device = handoff failure red flag",
        "",
    ]
    with open(os.path.join(HANDOFF, "MANIFEST.md"), "a", newline="\n") as f:
        f.write("\n".join(artifact_section))
    print(f"[handoff] artifact: {os.path.basename(ARTIFACT)} {size} B sha256={digest}")
else:
    print("[handoff] WARN: artifact not found:", ARTIFACT)
print("[handoff] manifest written:", os.path.join(HANDOFF, "MANIFEST.md"))
